export const api = {
  bootstrap:      ()        => req('/bootstrap'),
  createSession:  (payload) => req('/session', 'POST', payload),
  updateSession:  (id, payload) => req(`/session/${id}`, 'PATCH', payload),
  deleteSession:  (id)          => req(`/session/${id}`, 'DELETE'),
  logSet:         (payload) => req('/set', 'POST', payload),
  updateSet:      (id, payload) => req(`/set/${id}`, 'PATCH', payload),
  deleteSet:      (id) => req(`/set/${id}`, 'DELETE'),
  logCardio:      (payload) => req('/cardio', 'POST', payload),
  updateCardio:   (id, payload) => req(`/cardio/${id}`, 'PATCH', payload),
  deleteCardio:   (id)       => req(`/cardio/${id}`, 'DELETE'),
  createSuperset: (payload) => req('/superset', 'POST', payload),
  logWeight:      (payload) => req('/weight', 'POST', payload),
  listWeights:    (limit = 5) => req(`/weight?limit=${limit}`),
  // Daily Mobility. The server derives completion from the pain/stiffness
  // check-in plus checklist rows; there is no explicit "complete" endpoint.
  mobilityCatalog:     (dateKey)  => req(dateKey ? `/mobility/catalog?date=${encodeURIComponent(dateKey)}` : '/mobility/catalog'),
  mobilitySession:     (dateKey)  => req(`/mobility/session?date=${encodeURIComponent(dateKey)}`),
  saveMobilityCheckin: (payload)  => req('/mobility/session', 'POST', payload),
  toggleMobilityDrill: (payload)  => req('/mobility/checklist', 'POST', payload),
  mobilitySummary:     (dateKey, days = 14) => req(`/mobility/summary?date=${encodeURIComponent(dateKey)}&days=${days}`),
  mobilityRewards:     ()         => req('/mobility/rewards'),
  createMobilityReward:(payload)  => req('/mobility/rewards', 'POST', payload),
  redeemMobilityReward:(rewardId) => req('/mobility/rewards/redeem', 'POST', { reward_id: rewardId }),
};
