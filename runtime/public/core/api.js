export { cachedRead, pendingMobility } from "./offline.js";
// Mini App → Dashboard API client.
// Auth model:
//   Primary — Telegram initData (HMAC-signed by bot token). Sent as
//             Authorization: tma <initData>. Verified server-side.
//   First-party PWA — signed HttpOnly session cookie, issued by the protected
//                     dashboard gateway. JavaScript sends an auth-mode marker.
//   Dev fallback — static bearer token from config.js. ONLY accepted by
//                  the server when the request origin is localhost, so it
//                  can't be abused from the public deploy.
// This means the production bundle ships with no secrets: initData is
// generated by Telegram at app-open time, signed with a server-side key
// the client never sees.

const tg = typeof window !== 'undefined' ? window.Telegram?.WebApp : null;
const cfg = typeof window !== 'undefined' ? (window.MINIAPP_CONFIG || {}) : {};
const API_BASE = (cfg.apiBase || '').replace(/\/$/, '');
const DEV_TOKEN = cfg.token || '';

function hasTelegramInitData() {
  return !!(tg?.initData && typeof tg.initData === 'string' && tg.initData.length > 0);
}

function authHeader() {
  // Inside Telegram: signed initData — no static secrets leave the server.
  if (hasTelegramInitData()) return `tma ${tg.initData}`;
  // Outside Telegram (browser preview, localhost dev): bearer token.
  if (DEV_TOKEN) return `Bearer ${DEV_TOKEN}`;
  return 'PWA';
}

// --- Sync state (observable) ---
let _state = { status: 'idle', message: null, lastSyncAt: null };
const _listeners = new Set();
export function onSyncChange(fn) { _listeners.add(fn); return () => _listeners.delete(fn); }
export function getSyncState() { return { ..._state }; }
function setState(next) {
  _state = { ..._state, ...next };
  _listeners.forEach(fn => { try { fn(_state); } catch (_) {} });
}

// Expose current auth mode for telemetry / UI.
export function currentAuthMode() {
  if (hasTelegramInitData()) return 'hmac';
  if (DEV_TOKEN) return 'bearer-dev';
  return 'pwa';
}

// --- Raw fetch helper ---
async function networkReq(path, method = 'GET', body = null) {
  if (!API_BASE) {
    setState({ status: 'error', message: 'API base not configured' });
    throw new Error('API base not configured');
  }
  const auth = authHeader();
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 8000);
  setState({ status: 'syncing', message: null });
  try {
    const res = await fetch(`${API_BASE}${path}`, {
      method,
      signal: controller.signal,
      credentials: 'same-origin',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': auth,
      },
      body: body ? JSON.stringify(body) : undefined,
    });
    const text = await res.text();
    let data;
    try { data = text ? JSON.parse(text) : {}; } catch { data = { raw: text }; }
    if (!res.ok) {
      const msg = data.error || `HTTP ${res.status}`;
      // Preserve Retry-After for rate-limit backoff on the caller side.
      const retryAfter = res.headers.get('retry-after');
      setState({ status: 'error', message: msg });
      const err = new Error(msg);
      err.status = res.status;
      err.data = data;
      if (retryAfter) err.retryAfterSec = Number(retryAfter);
      throw err;
    }
    setState({ status: 'idle', message: null, lastSyncAt: Date.now() });
    return data;
  } catch (e) {
    if (_state.status !== 'error') {
      setState({ status: 'error', message: e?.message || 'Network error' });
    }
    throw e;
  } finally { clearTimeout(timeout); }
}

const cacheable = (path) => path === '/bootstrap' || path.startsWith('/mobility/');
export async function syncMobilityOutbox() {
  if (navigator.onLine === false) return;
  await flushMobility(networkReq);
}
async function req(path, method = 'GET', body = null) {
  if (method === 'POST' && ['/mobility/session', '/mobility/checklist'].includes(path)) {
    enqueueMobility(path, body);
    try { await syncMobilityOutbox(); }
    catch (error) {
      if (error.status && error.status < 500) throw error;
    }
    if (pendingMobility().length) {
      setState({ status: 'error', message: 'Saved on this device · waiting to sync' });
      return { queued: true };
    }
    return req(`/mobility/session?date=${encodeURIComponent(body.date)}`);
  }
  try {
    if (navigator.onLine === false) throw new Error('Offline');
    const data = await networkReq(path, method, body);
    if (method === 'GET' && cacheable(path)) cacheRead(path, data);
    return data;
  } catch (error) {
    if (method === 'GET' && cacheable(path) && !error.status) {
      const cached = cachedRead(path);
      if (cached) return cached;
    }
    throw error;
  }
}

